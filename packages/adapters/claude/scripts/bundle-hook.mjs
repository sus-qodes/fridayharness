// Bundles the Claude Code hook launcher into one dependency-free ES module (plan M1.10):
// src/hooks/entry.ts -> dist/hook.mjs. `friday harness config claude-code` copies that file into
// the target repository as .friday/harness/claude-code/hook.mjs, so it must not contain machine
// paths or secrets and must run on plain Node >= 22 with no node_modules.
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const pkgDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function launcherVersion() {
  const src = readFileSync(path.join(pkgDir, 'src', 'hooks', 'launcher.ts'), 'utf8');
  return /LAUNCHER_VERSION = '([^']+)'/.exec(src)?.[1] ?? '0.0.0';
}

export async function bundleHook(outfile = path.join(pkgDir, 'dist', 'hook.mjs')) {
  const version = launcherVersion();
  await build({
    entryPoints: [path.join(pkgDir, 'src', 'hooks', 'entry.ts')],
    outfile,
    absWorkingDir: pkgDir,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    // Workspace packages resolve to their TypeScript sources, so no prior build is needed.
    conditions: ['development'],
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'warning',
    banner: {
      js: [
        `// friday-hook-launcher-version: ${version}`,
        '// Friday hook launcher for Claude Code. Generated by "friday harness config claude-code"; do not edit.',
        '// It contains no secrets and no machine-specific paths, so it is safe to commit.',
        "import { createRequire as __fridayCreateRequire } from 'node:module';",
        'const require = __fridayCreateRequire(import.meta.url);',
      ].join('\n'),
    },
  });
  return { outfile, version };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const { outfile, version } = await bundleHook();
  process.stdout.write(`bundled hook launcher ${version} -> ${path.relative(process.cwd(), outfile)}\n`);
}
